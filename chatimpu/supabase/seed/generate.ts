/**
 * Generates supabase/seed.sql from the app's sample data (app/src/data) so the
 * mobile app (demo mode), CMS and database all share one source of truth.
 *   npx tsx supabase/seed/generate.ts > supabase/seed.sql
 */
import { STATES, DISTRICTS, MANDALS, VILLAGES } from '../../app/src/data/locations';
import { STORIES } from '../../app/src/data/stories';
import { POLLS, MAGAZINES, ALERTS, ADS, VIDEOS } from '../../app/src/data/catalog';
import en from '../../app/src/i18n/strings/en';
import te from '../../app/src/i18n/strings/te';
import hi from '../../app/src/i18n/strings/hi';
import { LANGUAGES } from '../../app/src/i18n/languages';

const q = (v: unknown): string =>
  v === null || v === undefined ? 'null'
  : typeof v === 'number' || typeof v === 'boolean' ? String(v)
  : Array.isArray(v) && v.every((x) => typeof x === 'string') ? `array[${v.map(q).join(',')}]::text[]`
  : typeof v === 'object' ? `${q(JSON.stringify(v))}::jsonb`
  : `'${String(v).replace(/'/g, "''")}'`;
const pt = (lat: number, lng: number) => `st_point(${lng}, ${lat})::geography`;
const rows = (table: string, cols: string[], values: string[][]) =>
  values.length ? `insert into ${table} (${cols.join(', ')}) values\n  ${values.map((r) => `(${r.join(', ')})`).join(',\n  ')}\non conflict do nothing;\n` : '';

const out: string[] = ['-- generated by supabase/seed/generate.ts — do not edit by hand', 'begin;'];
out.push(rows('languages', ['code', 'native', 'english'], LANGUAGES.map((l) => [q(l.code), q(l.native), q(l.english)])));
const cats = Object.keys(en).filter((k) => k.startsWith('cat_')).map((k) => k.slice(4));
out.push(rows('categories', ['id', 'sort'], cats.map((c, i) => [q(c), String(i)])));
out.push(rows('category_names', ['category_id', 'lang', 'name'], cats.flatMap((c) => ([['en', en], ['te', te], ['hi', hi]] as const).map(([l, t]) => [q(c), q(l), q((t as Record<string, string>)[`cat_${c}`])]))));
out.push(rows('states', ['id', 'name', 'name_te'], STATES.map((s) => [q(s.id), q(s.name), q(s.nameTe)])));
out.push(rows('districts', ['id', 'state_id', 'name', 'name_te', 'geo'], DISTRICTS.map((d) => [q(d.id), q(d.stateId), q(d.name), q(d.nameTe), pt(d.lat, d.lng)])));
out.push(rows('mandals', ['id', 'district_id', 'name', 'name_te', 'geo'], MANDALS.map((m) => [q(m.id), q(m.districtId), q(m.name), q(m.nameTe), pt(m.lat, m.lng)])));
out.push(rows('villages', ['id', 'mandal_id', 'name', 'name_te'], VILLAGES.map((v) => [q(v.id), q(v.mandalId), q(v.name), q(v.nameTe)])));

// relative publish times so the seed always looks fresh
const rel = (iso: string) => `now() - interval '${Math.round((Date.now() - new Date(iso).getTime()) / 60000)} minutes'`;
out.push(rows('stories', ['id', 'category_id', 'state_id', 'district_id', 'mandal_id', 'village_id', 'geo', 'image_path', 'source', 'status', 'published_at', 'is_breaking', 'sponsor', 'views', 'shares', 'comment_count'],
  STORIES.map((s) => [q(s.id), q(s.category), q(s.stateId), q(s.districtId), q(s.mandalId), q(s.villageId), pt(s.lat, s.lng), q(s.image), q(s.source), q('published'), rel(s.publishedAt), q(!!s.isBreaking), q(s.sponsor), String(s.views), String(s.shares), String(s.comments)])));
out.push(rows('story_translations', ['story_id', 'lang', 'headline', 'summary'],
  STORIES.flatMap((s) => Object.entries(s.content).map(([l, t]) => [q(s.id), q(l), q(t!.headline), q(t!.summary)]))));

for (const p of POLLS) {
  out.push(`insert into polls (id, category_id, closes_at) values (${q(p.id)}, ${q(p.category)}, now() + interval '${Math.round((new Date(p.closesAt).getTime() - Date.now()) / 3.6e6)} hours') on conflict do nothing;`);
  out.push(rows('poll_questions', ['poll_id', 'lang', 'question'], Object.entries(p.question).map(([l, v]) => [q(p.id), q(l), q(v)])));
  out.push(rows('poll_options', ['poll_id', 'id', 'sort'], p.options.map((o, i) => [q(p.id), q(o.id), String(i)])));
  out.push(rows('poll_option_labels', ['poll_id', 'option_id', 'lang', 'label'], p.options.flatMap((o) => Object.entries(o.label).map(([l, v]) => [q(p.id), q(o.id), q(l), q(v)]))));
}
out.push(rows('magazines', ['id', 'theme', 'cover_path', 'title', 'subtitle'], MAGAZINES.map((m) => [q(m.id), q(m.theme), q(m.cover), q(m.title), q(m.subtitle)])));
out.push(rows('magazine_stories', ['magazine_id', 'story_id', 'sort'], MAGAZINES.flatMap((m) => m.storyIds.map((s, i) => [q(m.id), q(s), String(i)]))));
out.push(rows('local_alerts', ['id', 'kind', 'severity', 'district_id', 'mandal_id', 'geo', 'title', 'detail', 'starts_at', 'ends_at'],
  ALERTS.map((a) => [q(a.id), q(a.kind), q(a.severity), q(a.districtId), q(a.mandalId), pt(a.lat, a.lng), q(a.title), q(a.detail), q(a.startsAt), q(a.endsAt)])));
out.push(rows('ads', ['id', 'district_ids', 'image_path', 'headline', 'body', 'cta', 'url', 'status', 'budget_inr', 'impressions', 'clicks'],
  ADS.map((a) => [q(a.id), a.districtIds === 'all' ? 'null' : q(a.districtIds), q(a.image), q(a.headline), q(a.body), q(a.cta), q(a.url), q(a.status), String(a.budgetInr), String(a.impressions), String(a.clicks)])));
out.push(rows('videos', ['id', 'story_id', 'video_path', 'poster_path', 'district_id', 'category_id', 'duration_sec', 'caption', 'subtitles', 'likes', 'shares'],
  VIDEOS.map((v) => [q(v.id), q(v.storyId), q(v.uri), q(v.poster), q(v.districtId), q(v.category), String(v.durationSec), q(v.caption), q(v.subtitles), String(v.likes), String(v.shares)])));
out.push('commit;');
console.log(out.join('\n'));
